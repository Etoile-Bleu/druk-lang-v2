use inkwell::attributes::{Attribute, AttributeLoc};
use inkwell::context::Context;
use inkwell::execution_engine::ExecutionEngine;
use inkwell::module::Module;
use inkwell::types::{AnyType, StructType};
use inkwell::values::FunctionValue;
use inkwell::AddressSpace;

pub(crate) struct RuntimeFns<'ctx> {
    pub(crate) print: FunctionValue<'ctx>,
    pub(crate) make_string: FunctionValue<'ctx>,
    pub(crate) make_array: FunctionValue<'ctx>,
    pub(crate) array_get: FunctionValue<'ctx>,
    pub(crate) array_set: FunctionValue<'ctx>,
    pub(crate) values_equal: FunctionValue<'ctx>,
    pub(crate) is_truthy: FunctionValue<'ctx>,
    pub(crate) push_frame: FunctionValue<'ctx>,
    pub(crate) pop_frame: FunctionValue<'ctx>,
    pub(crate) sret_attr: Attribute,
    pub(crate) byval_attr: Attribute,
}

impl<'ctx> RuntimeFns<'ctx> {
    /// Every `druk_rt_*` function is declared against the real Windows x64
    /// "C" ABI for a struct over 8 bytes, rather than against the plain IR
    /// shape `{i64, i64}` would suggest: an `RtValue` return goes through an
    /// explicit leading `sret` output pointer, and an `RtValue` parameter
    /// goes through a `byval` pointer to a caller-made copy, in both cases
    /// because that is what rustc's own ABI lowering does for
    /// `druk-runtime`'s real `extern "C" fn`s — our generated call sites
    /// have to match that exactly or the two sides disagree about which
    /// register holds which argument. Calls between two Druk functions
    /// (both generated by this same codegen) don't need either: LLVM lowers
    /// a bare struct parameter/return the same way on both ends of a call
    /// it compiles itself.
    pub(crate) fn declare(
        context: &'ctx Context,
        module: &Module<'ctx>,
        value_ty: StructType<'ctx>,
    ) -> Self {
        let i64_t = context.i64_type();
        let ptr_t = context.ptr_type(AddressSpace::default());
        let void_t = context.void_type();
        let sret_kind_id = Attribute::get_named_enum_kind_id("sret");
        let sret_attr = context.create_type_attribute(sret_kind_id, value_ty.as_any_type_enum());
        let byval_kind_id = Attribute::get_named_enum_kind_id("byval");
        let byval_attr = context.create_type_attribute(byval_kind_id, value_ty.as_any_type_enum());

        let print = module.add_function(
            "druk_rt_print",
            void_t.fn_type(&[ptr_t.into()], false),
            None,
        );
        let make_string = module.add_function(
            "druk_rt_make_string",
            void_t.fn_type(&[ptr_t.into(), ptr_t.into(), i64_t.into()], false),
            None,
        );
        let make_array = module.add_function(
            "druk_rt_make_array",
            void_t.fn_type(&[ptr_t.into(), ptr_t.into(), i64_t.into()], false),
            None,
        );
        let array_get = module.add_function(
            "druk_rt_array_get",
            void_t.fn_type(&[ptr_t.into(), ptr_t.into(), ptr_t.into()], false),
            None,
        );
        let array_set = module.add_function(
            "druk_rt_array_set",
            void_t.fn_type(
                &[ptr_t.into(), ptr_t.into(), ptr_t.into(), ptr_t.into()],
                false,
            ),
            None,
        );
        let values_equal = module.add_function(
            "druk_rt_values_equal",
            void_t.fn_type(&[ptr_t.into(), ptr_t.into(), ptr_t.into()], false),
            None,
        );
        let is_truthy = module.add_function(
            "druk_rt_is_truthy",
            i64_t.fn_type(&[ptr_t.into()], false),
            None,
        );
        let push_frame = module.add_function(
            "druk_rt_push_frame",
            void_t.fn_type(&[ptr_t.into(), i64_t.into()], false),
            None,
        );
        let pop_frame = module.add_function("druk_rt_pop_frame", void_t.fn_type(&[], false), None);

        for function in [make_string, make_array, array_get, array_set, values_equal] {
            function.add_attribute(AttributeLoc::Param(0), sret_attr);
        }
        print.add_attribute(AttributeLoc::Param(0), byval_attr);
        is_truthy.add_attribute(AttributeLoc::Param(0), byval_attr);
        for (function, byval_params) in [
            (array_get, [1, 2].as_slice()),
            (array_set, [1, 2, 3].as_slice()),
            (values_equal, [1, 2].as_slice()),
        ] {
            for &param in byval_params {
                function.add_attribute(AttributeLoc::Param(param), byval_attr);
            }
        }

        Self {
            print,
            make_string,
            make_array,
            array_get,
            array_set,
            values_equal,
            is_truthy,
            push_frame,
            pop_frame,
            sret_attr,
            byval_attr,
        }
    }

    pub(crate) fn map_into(&self, engine: &ExecutionEngine) {
        engine.add_global_mapping(
            &self.print,
            druk_runtime::druk_rt_print as *const () as usize,
        );
        engine.add_global_mapping(
            &self.make_string,
            druk_runtime::druk_rt_make_string as *const () as usize,
        );
        engine.add_global_mapping(
            &self.make_array,
            druk_runtime::druk_rt_make_array as *const () as usize,
        );
        engine.add_global_mapping(
            &self.array_get,
            druk_runtime::druk_rt_array_get as *const () as usize,
        );
        engine.add_global_mapping(
            &self.array_set,
            druk_runtime::druk_rt_array_set as *const () as usize,
        );
        engine.add_global_mapping(
            &self.values_equal,
            druk_runtime::druk_rt_values_equal as *const () as usize,
        );
        engine.add_global_mapping(
            &self.is_truthy,
            druk_runtime::druk_rt_is_truthy as *const () as usize,
        );
        engine.add_global_mapping(
            &self.push_frame,
            druk_runtime::druk_rt_push_frame as *const () as usize,
        );
        engine.add_global_mapping(
            &self.pop_frame,
            druk_runtime::druk_rt_pop_frame as *const () as usize,
        );
    }
}
