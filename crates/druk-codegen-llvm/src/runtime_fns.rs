use inkwell::context::Context;
use inkwell::execution_engine::ExecutionEngine;
use inkwell::module::Module;
use inkwell::values::FunctionValue;
use inkwell::AddressSpace;

pub(crate) struct RuntimeFns<'ctx> {
    pub(crate) print: FunctionValue<'ctx>,
    pub(crate) make_string: FunctionValue<'ctx>,
    pub(crate) make_array: FunctionValue<'ctx>,
    pub(crate) array_get: FunctionValue<'ctx>,
    pub(crate) array_set: FunctionValue<'ctx>,
    pub(crate) values_equal: FunctionValue<'ctx>,
    pub(crate) is_truthy: FunctionValue<'ctx>,
    pub(crate) make_struct: FunctionValue<'ctx>,
    pub(crate) struct_get: FunctionValue<'ctx>,
    pub(crate) struct_set: FunctionValue<'ctx>,
    pub(crate) push_frame: FunctionValue<'ctx>,
    pub(crate) pop_frame: FunctionValue<'ctx>,
    pub(crate) make_closure: FunctionValue<'ctx>,
    pub(crate) closure_function_ptr: FunctionValue<'ctx>,
    pub(crate) closure_get_capture: FunctionValue<'ctx>,
    pub(crate) len: FunctionValue<'ctx>,
    pub(crate) push: FunctionValue<'ctx>,
    pub(crate) pop: FunctionValue<'ctx>,
    pub(crate) typeof_: FunctionValue<'ctx>,
    pub(crate) input: FunctionValue<'ctx>,
    pub(crate) argv: FunctionValue<'ctx>,
    pub(crate) argc: FunctionValue<'ctx>,
}

impl<'ctx> RuntimeFns<'ctx> {
    /// Every `druk_rt_*` function that takes or returns an `RtValue` does so
    /// through a plain pointer, never by value. See the module doc comment
    /// on `druk_runtime` for why: a 16-byte struct crosses the Windows x64
    /// "C" ABI through a hidden `sret` slot and `byval` argument copies, but
    /// the x86-64 SysV ABI (Linux, macOS) returns and passes the same struct
    /// directly in registers. A plain pointer needs neither, so declaring
    /// every one of these parameters as `ptr` and nothing else keeps this
    /// call site correct on every platform without this crate needing to
    /// know which one it's targeting. Calls between two Druk functions
    /// (both generated by this same codegen) don't need pointer indirection
    /// at all: LLVM lowers a bare struct parameter/return the same way on
    /// both ends of a call it compiles itself.
    pub(crate) fn declare(context: &'ctx Context, module: &Module<'ctx>) -> Self {
        let i64_t = context.i64_type();
        let ptr_t = context.ptr_type(AddressSpace::default());
        let void_t = context.void_type();

        let print = module.add_function(
            "druk_rt_print",
            void_t.fn_type(&[ptr_t.into()], false),
            None,
        );
        let make_string = module.add_function(
            "druk_rt_make_string",
            void_t.fn_type(&[ptr_t.into(), ptr_t.into(), i64_t.into()], false),
            None,
        );
        let make_array = module.add_function(
            "druk_rt_make_array",
            void_t.fn_type(&[ptr_t.into(), ptr_t.into(), i64_t.into()], false),
            None,
        );
        let array_get = module.add_function(
            "druk_rt_array_get",
            void_t.fn_type(&[ptr_t.into(), ptr_t.into(), ptr_t.into()], false),
            None,
        );
        let array_set = module.add_function(
            "druk_rt_array_set",
            void_t.fn_type(
                &[ptr_t.into(), ptr_t.into(), ptr_t.into(), ptr_t.into()],
                false,
            ),
            None,
        );
        let values_equal = module.add_function(
            "druk_rt_values_equal",
            void_t.fn_type(&[ptr_t.into(), ptr_t.into(), ptr_t.into()], false),
            None,
        );
        let is_truthy = module.add_function(
            "druk_rt_is_truthy",
            i64_t.fn_type(&[ptr_t.into()], false),
            None,
        );
        let make_struct = module.add_function(
            "druk_rt_make_struct",
            void_t.fn_type(&[ptr_t.into(), ptr_t.into(), i64_t.into()], false),
            None,
        );
        let struct_get = module.add_function(
            "druk_rt_struct_get",
            void_t.fn_type(
                &[ptr_t.into(), ptr_t.into(), ptr_t.into(), i64_t.into()],
                false,
            ),
            None,
        );
        let struct_set = module.add_function(
            "druk_rt_struct_set",
            void_t.fn_type(
                &[
                    ptr_t.into(),
                    ptr_t.into(),
                    ptr_t.into(),
                    i64_t.into(),
                    ptr_t.into(),
                ],
                false,
            ),
            None,
        );
        let push_frame = module.add_function(
            "druk_rt_push_frame",
            void_t.fn_type(&[ptr_t.into(), i64_t.into()], false),
            None,
        );
        let pop_frame = module.add_function("druk_rt_pop_frame", void_t.fn_type(&[], false), None);
        let make_closure = module.add_function(
            "druk_rt_make_closure",
            void_t.fn_type(
                &[ptr_t.into(), i64_t.into(), ptr_t.into(), i64_t.into()],
                false,
            ),
            None,
        );
        let closure_function_ptr = module.add_function(
            "druk_rt_closure_function_ptr",
            i64_t.fn_type(&[ptr_t.into()], false),
            None,
        );
        let closure_get_capture = module.add_function(
            "druk_rt_closure_get_capture",
            void_t.fn_type(&[ptr_t.into(), ptr_t.into(), i64_t.into()], false),
            None,
        );
        let len = module.add_function(
            "druk_rt_len",
            void_t.fn_type(&[ptr_t.into(), ptr_t.into()], false),
            None,
        );
        let push = module.add_function(
            "druk_rt_push",
            void_t.fn_type(&[ptr_t.into(), ptr_t.into(), ptr_t.into()], false),
            None,
        );
        let pop = module.add_function(
            "druk_rt_pop",
            void_t.fn_type(&[ptr_t.into(), ptr_t.into()], false),
            None,
        );
        let typeof_ = module.add_function(
            "druk_rt_typeof",
            void_t.fn_type(&[ptr_t.into(), ptr_t.into()], false),
            None,
        );
        let input = module.add_function(
            "druk_rt_input",
            void_t.fn_type(&[ptr_t.into()], false),
            None,
        );
        let argv =
            module.add_function("druk_rt_argv", void_t.fn_type(&[ptr_t.into()], false), None);
        let argc =
            module.add_function("druk_rt_argc", void_t.fn_type(&[ptr_t.into()], false), None);

        Self {
            print,
            make_string,
            make_array,
            array_get,
            array_set,
            values_equal,
            is_truthy,
            make_struct,
            struct_get,
            struct_set,
            push_frame,
            pop_frame,
            make_closure,
            closure_function_ptr,
            closure_get_capture,
            len,
            push,
            pop,
            typeof_,
            input,
            argv,
            argc,
        }
    }

    pub(crate) fn map_into(&self, engine: &ExecutionEngine) {
        engine.add_global_mapping(
            &self.print,
            druk_runtime::druk_rt_print as *const () as usize,
        );
        engine.add_global_mapping(
            &self.make_string,
            druk_runtime::druk_rt_make_string as *const () as usize,
        );
        engine.add_global_mapping(
            &self.make_array,
            druk_runtime::druk_rt_make_array as *const () as usize,
        );
        engine.add_global_mapping(
            &self.array_get,
            druk_runtime::druk_rt_array_get as *const () as usize,
        );
        engine.add_global_mapping(
            &self.array_set,
            druk_runtime::druk_rt_array_set as *const () as usize,
        );
        engine.add_global_mapping(
            &self.values_equal,
            druk_runtime::druk_rt_values_equal as *const () as usize,
        );
        engine.add_global_mapping(
            &self.is_truthy,
            druk_runtime::druk_rt_is_truthy as *const () as usize,
        );
        engine.add_global_mapping(
            &self.make_struct,
            druk_runtime::druk_rt_make_struct as *const () as usize,
        );
        engine.add_global_mapping(
            &self.struct_get,
            druk_runtime::druk_rt_struct_get as *const () as usize,
        );
        engine.add_global_mapping(
            &self.struct_set,
            druk_runtime::druk_rt_struct_set as *const () as usize,
        );
        engine.add_global_mapping(
            &self.push_frame,
            druk_runtime::druk_rt_push_frame as *const () as usize,
        );
        engine.add_global_mapping(
            &self.pop_frame,
            druk_runtime::druk_rt_pop_frame as *const () as usize,
        );
        engine.add_global_mapping(
            &self.make_closure,
            druk_runtime::druk_rt_make_closure as *const () as usize,
        );
        engine.add_global_mapping(
            &self.closure_function_ptr,
            druk_runtime::druk_rt_closure_function_ptr as *const () as usize,
        );
        engine.add_global_mapping(
            &self.closure_get_capture,
            druk_runtime::druk_rt_closure_get_capture as *const () as usize,
        );
        engine.add_global_mapping(&self.len, druk_runtime::druk_rt_len as *const () as usize);
        engine.add_global_mapping(&self.push, druk_runtime::druk_rt_push as *const () as usize);
        engine.add_global_mapping(&self.pop, druk_runtime::druk_rt_pop as *const () as usize);
        engine.add_global_mapping(
            &self.typeof_,
            druk_runtime::druk_rt_typeof as *const () as usize,
        );
        engine.add_global_mapping(
            &self.input,
            druk_runtime::druk_rt_input as *const () as usize,
        );
        engine.add_global_mapping(&self.argv, druk_runtime::druk_rt_argv as *const () as usize);
        engine.add_global_mapping(&self.argc, druk_runtime::druk_rt_argc as *const () as usize);
    }
}
